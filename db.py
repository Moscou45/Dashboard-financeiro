ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"
DB_PATH = DATA_DIR / "dashboard.db"
SEED_PATH = ROOT / "initial_data.json"


def _secret_database_url() -> str | None:
    try:
        value = st.secrets.get("database", {}).get("url")
        if value:
            return value
    except Exception:
        pass
    local_secrets = ROOT / ".streamlit" / "secrets.toml"
    if local_secrets.exists():
        try:
            return tomllib.loads(local_secrets.read_text(encoding="utf-8")).get("database", {}).get("url")
        except Exception:
            return None
    return None


def _database_url() -> str:
    value = os.getenv("DATABASE_URL") or _secret_database_url()
    if not value:
        DATA_DIR.mkdir(parents=True, exist_ok=True)
        return f"sqlite:///{DB_PATH.as_posix()}"
    value = value.strip()
    if value.startswith("postgres://"):
        value = "postgresql+psycopg://" + value[len("postgres://"):]
    elif value.startswith("postgresql://"):
        value = "postgresql+psycopg://" + value[len("postgresql://"):]
    if value.startswith("postgresql+") and "sslmode=" not in value:
        value += "&sslmode=require" if "?" in value else "?sslmode=require"
    return value


engine: Engine = create_engine(
    _database_url(),
    pool_pre_ping=True,
    connect_args={"check_same_thread": False} if _database_url().startswith("sqlite:") else {},
)


def _amount(value: Any) -> Decimal:
    return Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def _quantity(value: Any) -> Decimal:
    return Decimal(str(value)).quantize(Decimal("0.001"), rounding=ROUND_HALF_UP)


def initialize() -> None:
    id_definition = ("INTEGER PRIMARY KEY" if engine.dialect.name == "sqlite"
                     else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    with engine.begin() as con:
        con.execute(text(f"""
            CREATE TABLE IF NOT EXISTS transactions (
                id {id_definition},
                date TEXT NOT NULL,
                kind TEXT NOT NULL CHECK (kind IN ('Receita', 'Despesa')),
                category TEXT NOT NULL,
                amount NUMERIC(14, 2) NOT NULL,
                payment_method TEXT,
                expense_type TEXT,
                origin TEXT NOT NULL,
                dedupe_key TEXT UNIQUE
            )
        """))
        con.execute(text(f"""
            CREATE TABLE IF NOT EXISTS product_sales (
                id {id_definition},
                year INTEGER NOT NULL,
                month_num INTEGER,
                month_label TEXT NOT NULL,
                product TEXT NOT NULL,
                quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
                cost NUMERIC(14, 2) NOT NULL DEFAULT 0,
                revenue NUMERIC(14, 2) NOT NULL DEFAULT 0,
                profit NUMERIC(14, 2) NOT NULL DEFAULT 0,
                origin TEXT NOT NULL,
                dedupe_key TEXT UNIQUE
            )
        """))
        con.execute(text("""
            CREATE TABLE IF NOT EXISTS monthly_summary (
                year INTEGER NOT NULL,
                month INTEGER NOT NULL,
                revenue NUMERIC(14, 2) NOT NULL DEFAULT 0,
                expenses NUMERIC(14, 2) NOT NULL DEFAULT 0,
                PRIMARY KEY (year, month)
            )
        """))
        con.execute(text("CREATE INDEX IF NOT EXISTS idx_transactions_date ON transactions(date)"))
        con.execute(text("CREATE INDEX IF NOT EXISTS idx_product_sales_period ON product_sales(year, month_num)"))


def seed_initial_data() -> bool:
    """Seed a local preview only. Production history is loaded explicitly by seed_database.py."""
    app_env = os.getenv("APP_ENV", "").casefold()
    try:
        app_env = (st.secrets.get("APP_ENV", app_env) or app_env).casefold()
    except Exception:
        pass
    if app_env == "production" or engine.dialect.name != "sqlite":
        return False
    with engine.begin() as con:
        if con.execute(text("SELECT 1 FROM monthly_summary LIMIT 1")).first():
            return False
        if not SEED_PATH.exists():
            return False
        payload = json.loads(SEED_PATH.read_text(encoding="utf-8"))
        for month, values in payload.get("monthly_summary", {}).items():
            con.execute(text("""INSERT INTO monthly_summary(year, month, revenue, expenses)
                VALUES (:year, :month, :revenue, :expenses) ON CONFLICT DO NOTHING"""),
                {"year": payload.get("year", 2026), "month": int(month), "revenue": _amount(values["revenue"]), "expenses": _amount(values["expenses"])})
        for index, row in enumerate(payload.get("transactions", [])):
            key = hashlib.sha256(f"seed-tx-{index}-{row}".encode("utf-8")).hexdigest()
            expense_type = row.get("expense_type")
            if expense_type and str(expense_type).casefold().startswith("vari"):
                expense_type = "Variável"
            elif expense_type and str(expense_type).casefold().startswith("fix"):
                expense_type = "Fixa"
            con.execute(text("""INSERT INTO transactions
                (date, kind, category, amount, payment_method, expense_type, origin, dedupe_key)
                VALUES (:date, :kind, :category, :amount, :payment_method, :expense_type, 'base_excel', :dedupe_key)
                ON CONFLICT DO NOTHING"""),
                {"date": row["date"], "kind": row["kind"], "category": row["category"], "amount": _amount(row["amount"]),
                 "payment_method": row.get("payment_method"), "expense_type": expense_type, "dedupe_key": key})
        month_names = {"JANEIRO": 1, "FEVEREIRO": 2, "MARÇO": 3, "MARCO": 3, "ABRIL": 4, "MAIO": 5, "JUNHO": 6, "JULHO": 7, "AGOSTO": 8, "SETEMBRO": 9, "OUTUBRO": 10, "NOVEMBRO": 11, "DEZEMBRO": 12}
        for index, row in enumerate(payload.get("products", [])):
            label = str(row.get("month") or "Sem mês").strip()
            key = hashlib.sha256(f"seed-product-{index}-{row}".encode("utf-8")).hexdigest()
            con.execute(text("""INSERT INTO product_sales
                (year, month_num, month_label, product, quantity, cost, revenue, profit, origin, dedupe_key)
                VALUES (:year, :month_num, :month_label, :product, :quantity, :cost, :revenue, :profit, 'base_excel', :dedupe_key)
                ON CONFLICT DO NOTHING"""),
                {"year": payload.get("year", 2026), "month_num": month_names.get(label.upper()), "month_label": label,
                 "product": row["product"], "quantity": _quantity(row["quantity"]), "cost": _amount(row["cost"]), "revenue": _amount(row["revenue"]),
                 "profit": _amount(row["profit"]), "dedupe_key": key})
    return True


